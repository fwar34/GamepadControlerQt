// =====================================================================
// ConfigManager —— 配置管理器
//
// 配置文件位于可执行文件所在目录（本机使用，不跨机器），
// 文件名与安卓版保持一致（steamlike_config.json）。
//
// 加载策略：
//   - 文件存在且可正常解析 -> 返回解析结果
//   - 文件不存在 / 解析失败 / 版本不匹配 -> 回退到默认配置并保存
// =====================================================================
// 【C++ 语法】#pragma once：头文件守卫（非标准但被 MSVC/GCC/Clang 等主流编译器支持），
// 确保本头文件在同一个编译单元中只被处理一次，避免因重复包含导致的重定义错误；
// 效果等同于传统的 #ifndef/#define/#endif 三段式写法，但更简洁
#pragma once

// 【C++ 语法】#include "..."：双引号形式表示"先查找当前源文件所在目录"再查找包含路径，
// 通常用于包含本项目内部的头文件；此处引入手柄映射相关的数据类型定义（如 ControllerProfile）
#include "MappingTypes.h"

// 【C++ 语法】#include <...>：尖括号形式表示直接到编译器/系统配置的包含路径中查找头文件，
// 通常用于标准库或第三方库；此处引入 Qt 的 QString（Unicode 字符串类）
#include <QString>

// =====================================================================
// ConfigManager —— 配置管理器
//
// 配置文件位于可执行文件所在目录（本机使用，不跨机器），
// 文件名与安卓版保持一致（steamlike_config.json）。
//
// 加载策略：
//   - 文件存在且可正常解析 -> 返回解析结果
//   - 文件不存在 / 解析失败 / 版本不匹配 -> 回退到默认配置并保存
// =====================================================================
// 【C++ 语法】class 声明：定义一个名为 ConfigManager 的类；类名后的 "{" 之前的成员
// 访问权限默认为 private（私有），即默认只有类内部可见
class ConfigManager {
// 【C++ 语法】public 访问说明符：自此处起，后续成员对外公开，可被其他类/函数
// 通过作用域运算符 "::" 以"类名::成员"的形式直接访问
public:
    // 配置文件完整路径（exe 目录 + "steamlike_config.json"）
    // 【C++ 语法】static 成员函数：属于类本身而非某个具体对象，不依赖对象实例，
    // 用 ConfigManager::configFilePath() 直接调用；无参数
    // 【C++ 语法】返回类型 QString：Qt 的字符串类（UTF-16 编码、隐式共享）
    static QString configFilePath();
    // 配置文件是否存在
    // 【C++ 语法】static 成员函数，返回内置类型 bool（true/false），表示"配置文件是否存在"
    static bool hasConfigFile();
    // 加载配置：文件不存在或解析失败时回退到默认配置并保存
    // 【C++ 语法】static 成员函数，按值返回 ControllerProfile 类型（手柄配置结构体，
    // 内部用 QVector 容器存储图层/按键映射数据）；"按值返回"意味着返回时发生一次拷贝/移动
    static ControllerProfile load();
    // 保存配置到文件，成功返回 true
    // 【C++ 语法】const ControllerProfile& profile：形参为"对常量对象的引用"——
    // 只读访问传入对象、不复制、也不允许修改它，从而避免按值传参的拷贝开销；
    // 【C++ 语法】返回 bool 表示保存是否成功，由调用方决定是否提示用户
    static bool save(const ControllerProfile& profile);
    // 重置为默认配置并保存
    // 【C++ 语法】static 成员函数，返回类型 void（无返回值），调用后不产生结果值
    static void resetToDefault();
// 【C++ 语法】} 结束 ConfigManager 类的定义；注意类定义结束时末尾有分号 ";"（类声明语句的结束符）
};
